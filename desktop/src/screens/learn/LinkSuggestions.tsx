// Review dialog for Gemini's suggested prerequisite links and missing tiles (LearnTileViewModel.acceptSuggestions).
import { useEffect, useState } from "react";
import { ArrowRight, Plus } from "lucide-react";
import type { MissingPrerequisite, SuggestedLink } from "@/ai/learning";
import * as ops from "@/domain/ops";
import { useBrain } from "@/store/brain";
import { Button, Dialog } from "@/ui/primitives";

export interface Suggestions {
  links: SuggestedLink[];
  missing: MissingPrerequisite[];
}

export function LinkSuggestionsDialog({ nodeId, suggestions, onClose }: { nodeId: string; suggestions: Suggestions | null; onClose: () => void }) {
  const nodes = useBrain((s) => s.brain.nodes);
  const commit = useBrain((s) => s.commit);
  const toast = useBrain((s) => s.toast);
  const [links, setLinks] = useState<Set<number>>(new Set());
  const [missing, setMissing] = useState<Set<number>>(new Set());

  useEffect(() => {
    setLinks(new Set(suggestions?.links.map((_, i) => i) ?? []));
    setMissing(new Set(suggestions?.missing.map((_, i) => i) ?? []));
  }, [suggestions]);

  if (!suggestions) return null;
  const name = (id: string) => nodes.find((n) => n.id === id)?.name ?? "Tile";
  const self = name(nodeId);
  const toggle = (set: Set<number>, update: (s: Set<number>) => void, i: number) => {
    const n = new Set(set);
    if (n.has(i)) n.delete(i);
    else n.add(i);
    update(n);
  };

  const accept = () => {
    const pickedLinks = suggestions.links.filter((_, i) => links.has(i));
    const pickedMissing = suggestions.missing.filter((_, i) => missing.has(i));
    let added = 0;
    commit((s) => {
      let next = s;
      for (const l of pickedLinks) {
        const linked = l.direction === "DEPENDS_ON" ? ops.addLearningLink(next, nodeId, l.tileId) : ops.addLearningLink(next, l.tileId, nodeId);
        if (linked) {
          next = linked;
          added++;
        }
      }
      for (const m of pickedMissing) {
        const [created, id] = ops.createNode(next, "MODEL", m.name);
        next = created;
        const linked = ops.addLearningLink(next, nodeId, id);
        if (linked) {
          next = linked;
          added++;
        }
      }
      return next;
    });
    const extra = pickedMissing.length ? ` · ${pickedMissing.length} new tile${pickedMissing.length === 1 ? "" : "s"} in Backlog` : "";
    toast(`Added ${added} link${added === 1 ? "" : "s"}${extra}`);
    onClose();
  };

  const count = links.size + missing.size;
  return (
    <Dialog
      open
      onClose={onClose}
      title="Suggested links"
      width="max-w-xl"
      footer={
        <>
          <Button variant="secondary" onClick={onClose}>Cancel</Button>
          <Button disabled={count === 0} onClick={accept}>Add {count}</Button>
        </>
      }
    >
      <div className="space-y-5">
        <div className="text-xs text-item">Generated by Gemini, verify.</div>
        {suggestions.links.length > 0 && (
          <div className="space-y-1.5">
            <div className="text-xs font-semibold uppercase tracking-wide text-muted">Existing tiles</div>
            {suggestions.links.map((l, i) => (
              <label key={l.tileId} className="flex cursor-pointer items-start gap-3 rounded-lg border border-hairline p-3 hover:border-electric/60">
                <input type="checkbox" className="mt-0.5 h-4 w-4 accent-navy" checked={links.has(i)} onChange={() => toggle(links, setLinks, i)} />
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-1.5 text-sm font-medium">
                    {l.direction === "DEPENDS_ON" ? (
                      <>{self} <ArrowRight size={13} className="text-item" /> depends on <span className="text-electric">{name(l.tileId)}</span></>
                    ) : (
                      <><span className="text-electric">{name(l.tileId)}</span> <ArrowRight size={13} className="text-item" /> depends on {self}</>
                    )}
                  </div>
                  {l.reason && <div className="mt-0.5 text-xs text-muted">{l.reason}</div>}
                </div>
              </label>
            ))}
          </div>
        )}
        {suggestions.missing.length > 0 && (
          <div className="space-y-1.5">
            <div className="text-xs font-semibold uppercase tracking-wide text-muted">Missing prerequisites · new Backlog tiles</div>
            {suggestions.missing.map((m, i) => (
              <label key={m.name} className="flex cursor-pointer items-start gap-3 rounded-lg border border-dashed border-hairline p-3 hover:border-electric/60">
                <input type="checkbox" className="mt-0.5 h-4 w-4 accent-navy" checked={missing.has(i)} onChange={() => toggle(missing, setMissing, i)} />
                <div className="min-w-0 flex-1">
                  <div className="flex items-center gap-1.5 text-sm font-medium"><Plus size={13} className="text-electric" />{m.name}</div>
                  {m.reason && <div className="mt-0.5 text-xs text-muted">{m.reason}</div>}
                </div>
              </label>
            ))}
          </div>
        )}
      </div>
    </Dialog>
  );
}
